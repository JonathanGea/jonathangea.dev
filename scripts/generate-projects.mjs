import { readdir, readFile, writeFile, mkdir, rm, cp, access } from 'node:fs/promises';
import { resolve, relative, sep } from 'node:path';
import { Marked } from 'marked';

const source = resolve('src/data');
const assets = resolve('public/content/projects');
const output = resolve('src/app/features/projects/generated-projects.ts');
const projects = [];
const localPath = async (folder, path) => {
  const file = resolve(folder, path);
  if (relative(folder, file).startsWith('..') || !relative(folder, file)) {
    throw new Error(`Invalid project asset: ${path}`);
  }
  await access(file);
  return file;
};
await rm(assets, { recursive: true, force: true });
await mkdir(assets, { recursive: true });
for (const entry of await readdir(source, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const folder = resolve(source, entry.name);
  const metadata = JSON.parse(await readFile(resolve(folder, 'metadata.json'), 'utf8'));
  if (metadata.slug !== entry.name || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(metadata.slug)) {
    throw new Error(`Invalid slug in ${entry.name}`);
  }
  for (const field of ['id', 'title', 'description', 'domain', 'type', 'cover']) {
    if (typeof metadata[field] !== 'string' || !metadata[field]) throw new Error(`${entry.name}: missing ${field}`);
  }
  if (!Array.isArray(metadata.tags) || !metadata.tags.every(tag => typeof tag === 'string') ||
      !Array.isArray(metadata.images) || !metadata.images.every(image => typeof image === 'string')) {
    throw new Error(`${entry.name}: tags and images must be string arrays`);
  }
  const assetUrl = async (path) => {
    if (/^https?:\/\//.test(path)) return path;
    const file = await localPath(folder, path);
    const assetPath = relative(folder, file).split(sep).join('/');
    const target = resolve(assets, entry.name, assetPath);
    await mkdir(resolve(target, '..'), { recursive: true });
    await cp(file, target);
    return `content/projects/${entry.name}/${assetPath}`;
  };
  const parser = new Marked({
    async: true,
    async walkTokens(token) {
      if (token.type === 'image') token.href = await assetUrl(token.href);
    }
  });
  const markdown = await readFile(resolve(folder, 'README.md'), 'utf8');
  // The page supplies its own title; keep the remaining Markdown intact.
  const contentHtml = await parser.parse(markdown.replace(/^# .*(?:\r?\n|$)/, ''));
  projects.push({ ...metadata, cover: await assetUrl(metadata.cover),
    images: await Promise.all(metadata.images.map(assetUrl)), contentHtml });
}
projects.sort((a, b) => (a.order ?? 0) - (b.order ?? 0) || a.slug.localeCompare(b.slug));
if (new Set(projects.map(p => p.id)).size !== projects.length) throw new Error('Duplicate project ID');
await writeFile(output, `// Generated by scripts/generate-projects.mjs. Edit src/data instead.\nimport type { Project } from './project.model';\n\nexport const PROJECTS: Project[] = ${JSON.stringify(projects, null, 2)};\n`);
console.log(`Generated ${projects.length} projects from src/data.`);
